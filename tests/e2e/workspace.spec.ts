test('real AVIF download and lossless metadata controls',async({page})=>{
  const jpeg=await sharp({create:{width:80,height:60,channels:3,background:'#8472b1'}}).withExif({IFD0:{Artist:'Browser fixture'}}).jpeg().toBuffer();
  await page.goto('/image-tools/image-converter');
  await page.locator('input[type=file]').setInputFiles({name:'fixture.jpg',mimeType:'image/jpeg',buffer:jpeg});
  await page.getByLabel('Output format').selectOption('avif');
  await page.getByRole('button',{name:'Convert 1 image',exact:true}).click();
  await expect(page.getByText('80 × 60 · AVIF')).toBeVisible();
  const downloading=page.waitForEvent('download');
  await page.getByRole('link',{name:'Download fixture.jpg as AVIF'}).click();
  const avif=await downloading;
  expect(avif.suggestedFilename()).toBe('fixture.avif');
  expect((await sharp(await readFile((await avif.path())!)).metadata()).format).toBe('heif');
  await page.goto('/image-tools/jpg-to-webp');
  await page.getByLabel('Lossless WebP',{exact:false}).check();
  await page.getByLabel('Remove metadata (EXIF)',{exact:false}).uncheck();
  await expect(page.getByRole('slider',{name:'Quality'})).toBeDisabled();
  await page.locator('input[type=file]').setInputFiles({name:'fixture.jpg',mimeType:'image/jpeg',buffer:jpeg});
  await page.getByRole('button',{name:'Convert 1 image',exact:true}).click();
  const downloadingWebp=page.waitForEvent('download');
  await page.getByRole('link',{name:'Download fixture.jpg as WebP'}).click();
  const webp=await downloadingWebp;
  const data=await readFile((await webp.path())!);
  expect((await sharp(data).metadata()).exif?.toString()).toContain('Browser fixture');
  expect(await sharp(data).raw().toBuffer()).toEqual(await sharp(jpeg).raw().toBuffer());
});
test('direct media permission, actual downloaded bytes and rejection states',async({page,request})=>{
 const png=await sharp({create:{width:24,height:16,channels:3,background:'#347'}}).png().toBuffer();
 await page.goto('/social-media-tools/direct-media-downloader');
 await expect(page.getByText('No cookies, login, private-network access or social-page extraction.')).toBeVisible();
 await expect(page.getByText('download PDF/JSON for the full SEO audit.',{exact:false})).toHaveCount(0);
 await expect(page.getByRole('button',{name:'Prepare download'})).toBeDisabled();
 await page.getByLabel('Direct media URL').fill('https://example.com/owned.png');
 await page.getByLabel('I own this media or have permission to download it.').check();
 await page.route('**/api/media',route=>route.fulfill({status:200,headers:{'Content-Type':'image/png','X-Media-Filename':'owned.png'},body:png}));
 await page.getByRole('button',{name:'Prepare download'}).click();
 const downloading=page.waitForEvent('download');await page.getByRole('link',{name:'Download file',exact:true}).click();
 const download=await downloading;expect(download.suggestedFilename()).toBe('owned.png');
 expect(await readFile((await download.path())!)).toEqual(png);
 await page.unroute('**/api/media');
 await page.getByLabel('Direct media URL').fill('http://169.254.169.254/a.mp4');
 await expect(page.getByRole('link',{name:'Download file',exact:true})).toHaveCount(0);
 await page.getByRole('button',{name:'Prepare download'}).click();
 await expect(page.getByRole('status')).toContainText('Private-network');
 const denied=await request.post('/api/media',{data:{url:'https://example.com/a.jpg',authorized:false}});expect(denied.status()).toBe(400);
});
test('real background-removal job completes through the browser and downloads an alpha PNG',async({page})=>{
 test.skip(process.env.MEDIA_JOBS_ENABLED!=='true','Requires a configured Postgres/Redis/worker installation (see docs/architecture.md).');
 const portrait=await sharp({create:{width:40,height:40,channels:3,background:'#c08060'}}).jpeg().toBuffer();
 await page.goto('/image-tools/background-remover');
 await page.getByLabel('Choose media file').setInputFiles({name:'portrait.jpg',mimeType:'image/jpeg',buffer:portrait});
 await page.getByRole('button',{name:'Start processing'}).click();
 await expect(page.getByRole('button',{name:'Download result'})).toBeVisible({timeout:30000});
 const downloading=page.waitForEvent('download');
 await page.getByRole('button',{name:'Download result'}).click();
 const download=await downloading;
 const data=await readFile((await download.path())!);
 const meta=await sharp(data).metadata();
 expect(meta.format).toBe('png');
 expect(meta.hasAlpha).toBe(true);
});
