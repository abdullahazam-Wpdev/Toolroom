  await page.getByRole("button",{name:"Open tool search"}).click(); await input.fill('AVIF');await input.press('Enter');
  await expect(page.locator('.tool-card')).toHaveCount(1);
  await expect(page.locator('.tool-title')).toContainText('Image converter');
  expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true);
